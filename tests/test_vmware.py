"""Checks the VMware capacity template and the vmware/grafana dashboards.

Both are generated by vmware/tools; the tests also make sure the committed
files are what the generators produce, so nobody edits the output by hand.
"""
import glob
import json
import os
import re
import subprocess
import sys
import tempfile
import unittest

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VMW = os.path.join(ROOT, 'vmware')
TEMPLATE = os.path.join(VMW, 'zbx_template_vmware_capacity.yaml')
DASHBOARDS = sorted(glob.glob(os.path.join(VMW, 'grafana', '*.json')))

# Names of the standard "VMware" / "VMware Hypervisor" template items the dashboards use.
STANDARD_NAMES = [
    'CPU usage', 'CPU usage in percent', 'Used memory', 'Total memory', 'CPU cores', 'CPU frequency',
    'Power usage', 'Power usage maximum allowed',
    'Free space on datastore [DS-01] (percentage)', 'Total size of datastore [DS-01]',
]
LLD_SAMPLES = {'{#DATASTORE}': 'DS-01', '{#CLUSTER.NAME}': 'Cluster-A'}
# Dashboard variables substituted by a sample value before matching.
VAR_SAMPLES = {'$datastore': 'DS-01', '$cluster': 'Cluster-A'}


def load_template():
    with open(TEMPLATE) as fh:
        return yaml.safe_load(fh)['zabbix_export']['templates'][0]


def prototypes(tpl):
    return [p for r in tpl['discovery_rules'] for p in r['item_prototypes']]


def all_uuids(node):
    if isinstance(node, dict):
        for k, v in node.items():
            if k == 'uuid':
                yield v
            else:
                yield from all_uuids(v)
    elif isinstance(node, list):
        for v in node:
            yield from all_uuids(v)


class TemplateTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tpl = load_template()
        cls.protos = prototypes(cls.tpl)
        with open(TEMPLATE) as fh:
            cls.text = fh.read()

    def test_uuids_are_unique_v4(self):
        uuids = list(all_uuids(self.tpl))
        self.assertEqual(len(uuids), len(set(uuids)))
        for u in uuids:
            self.assertRegex(u, r'^[0-9a-f]{12}4[0-9a-f]{3}[89ab][0-9a-f]{15}$')

    def test_item_keys_unique_and_namespaced(self):
        keys = [p['key'] for p in self.protos]
        self.assertEqual(len(keys), len(set(keys)))
        for k in keys:
            self.assertTrue(k.startswith('vmw.cap.'), k)

    def test_discovery_keys_differ_from_standard_template(self):
        # The standard VMware template owns the unquoted keys; duplicates would fail the link.
        for r in self.tpl['discovery_rules']:
            self.assertIn('["{$VMWARE.URL}"]', r['key'])

    def test_triggers_reference_own_prototypes(self):
        keys = {p['key'] for p in self.protos}
        refs = 0
        for p in self.protos:
            for t in p.get('trigger_prototypes', []):
                for expr in (t['expression'], t.get('recovery_expression', '')):
                    for key in re.findall(r'/VMware capacity planning/([^)]+)\)', expr):
                        self.assertIn(key, keys, t['name'])
                        refs += 1
        self.assertGreater(refs, 0)

    def test_warning_triggers_depend_on_high(self):
        for p in self.protos:
            for t in p.get('trigger_prototypes', []):
                if t['priority'] == 'WARNING':
                    self.assertTrue(t.get('dependencies'), t['name'])

    def test_used_macros_are_defined(self):
        defined = {m['macro'] for m in self.tpl['macros']}
        used = set(re.findall(r'\{\$VMW\.[A-Z.]+\}', self.text))
        self.assertEqual(used - defined, set())
        self.assertEqual(defined - used, set())

    def test_foreach_filters_match_two_parameter_keys(self):
        # vmware.hv.* keys take [url,uuid]; "[*]" would silently match nothing.
        refs = re.findall(r'/\*/(vmware\.hv\.[a-z.]+)\[([^\]]*)\]\?', self.text)
        self.assertTrue(refs)
        for key, params in refs:
            self.assertTrue(params.startswith('*,*'), key + '[' + params + ']')

    @staticmethod
    def is_helper(key):
        return key.split('[')[0].endswith(('.hist', '.tl'))

    def test_long_trends_for_year_over_year(self):
        for p in self.protos:
            if p.get('value_type', 'FLOAT') in ('FLOAT', 'UNSIGNED') and not self.is_helper(p['key']):
                self.assertEqual(p.get('trends'), '730d', p['key'])

    def test_timeleft_is_computed_once_per_forecast_in_a_helper_item(self):
        # Three copies of timeleft() in one formula tripled the history reads of every evaluation.
        by_key = {p['key']: p for p in self.protos}
        for p in self.protos:
            n = p['params'].count('timeleft(') if 'params' in p else 0
            self.assertLessEqual(n, 1, p['key'])
            if p['key'].split('[')[0].endswith('.daysleft'):
                self.assertEqual(n, 0, p['key'])
                hist = p['key'].replace('.daysleft', '.hist')
                tl = p['key'].replace('.daysleft', '.tl')
                self.assertIn(hist, by_key)
                self.assertIn(tl, by_key)
                self.assertIn(tl, p['params'])
                self.assertEqual(by_key[tl]['params'].count('timeleft('), 1, tl)
                self.assertNotIn('count(', p['params'])
        for key in by_key:
            if self.is_helper(key):
                self.assertEqual(by_key[key].get('trends'), '0', key)

    def test_history_check_survives_gaps_and_short_item_history(self):
        # trendcount over the whole period: one missing day does not reset it, and trends outlive a
        # short history setting of the source item. The shift is in days like the period.
        for p in self.protos:
            if p['key'].split('[')[0].endswith('.hist'):
                self.assertRegex(p['params'], r'^\(trendcount\(//.*,\{\$VMW\.FORECAST\.PERIOD\}:now/d-'
                                              r'\{\$VMW\.FORECAST\.MIN\.HISTORY\}\)>0\)$', p['key'])
        self.assertNotIn(' count(//', self.text)

    def test_forecast_problems_do_not_recover_on_no_forecast(self):
        # -1 means "no forecast right now": closing and reopening a real problem would notify twice.
        for p in self.protos:
            for t in p.get('trigger_prototypes', []):
                self.assertNotIn('<0', t['recovery_expression'], t['name'])

    def test_clusters_with_quote_or_backslash_are_not_discovered(self):
        rule = next(r for r in self.tpl['discovery_rules'] if r['key'].startswith('vmware.cluster'))
        cond = rule['filter']['conditions'][0]
        self.assertEqual((cond['macro'], cond['operator']), ('{#CLUSTER.NAME}', 'NOT_MATCHES_REGEX'))
        for bad in ('Prod "A"', 'a\\b'):
            self.assertTrue(re.search(cond['value'], bad), bad)
        for fine in ('Prod-A', 'Кластер 1', "it's"):
            self.assertFalse(re.search(cond['value'], fine), fine)

    def test_generator_output_is_committed(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = os.path.join(tmp, 't.yaml')
            subprocess.run([sys.executable, os.path.join(VMW, 'tools', 'gen_capacity_template.py'), out],
                           check=True, stdout=subprocess.DEVNULL)
            with open(out) as fh:
                self.assertEqual(fh.read(), self.text, 'regenerate vmware/zbx_template_vmware_capacity.yaml')


def known_names():
    names = list(STANDARD_NAMES)
    for p in prototypes(load_template()):
        name = p['name']
        for macro, value in LLD_SAMPLES.items():
            name = name.replace(macro, value)
        assert '{#' not in name, 'add a sample for ' + name
        names.append(name)
    return names


def item_matches(item_filter, name):
    for var, value in VAR_SAMPLES.items():
        item_filter = item_filter.replace(var, value)
    if item_filter.startswith('/') and item_filter.endswith('/'):
        return re.search(item_filter[1:-1], name) is not None
    return item_filter == name


def panels(dash):
    for p in dash['panels']:
        yield p
        for sub in p.get('panels', []):
            yield sub


class DashboardTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.names = known_names()
        cls.dashes = {}
        for path in DASHBOARDS:
            with open(path) as fh:
                cls.dashes[os.path.basename(path)] = json.load(fh)

    def test_three_dashboards(self):
        self.assertEqual(sorted(self.dashes),
                         ['vmware-cpu-memory.json', 'vmware-datastores.json', 'vmware-power.json'])

    def test_every_item_filter_matches_an_item(self):
        for fname, d in self.dashes.items():
            for p in panels(d):
                for t in p.get('targets', []):
                    if 'item' not in t:
                        continue
                    flt = t['item']['filter']
                    with self.subTest(dashboard=fname, panel=p['title']):
                        self.assertTrue(any(item_matches(flt, n) for n in self.names),
                                        '%r matches no item' % flt)

    def test_variable_queries_match_items(self):
        for fname, d in self.dashes.items():
            for v in d['templating']['list']:
                item = (v.get('query') or {}).get('item') if v['type'] == 'query' else None
                if item:
                    self.assertTrue(any(item_matches(item, n) for n in self.names), (fname, v['name']))
                    self.assertEqual(v.get('refresh'), 2, (fname, v['name']))

    def test_vcenter_group_default(self):
        # Defaults to "vCenter"; the groups VMware creates for discovered hosts are not offered.
        for fname, d in self.dashes.items():
            v = next(v for v in d['templating']['list'] if v['name'] == 'vcgroup')
            self.assertEqual(v['current']['value'], 'vCenter', fname)
            rx_ = re.compile(v['regex'][1:-1])
            for group in ('vCenter', 'VMware vCenters', 'Zabbix servers'):
                self.assertTrue(rx_.match(group), group)
            for group in ('Cluster-A (hypervisor)', 'Cluster-A (vm)', 'Discovered hosts', 'Templates/Applications'):
                self.assertFalse(rx_.match(group), group)

    def test_no_server_side_expressions(self):
        # Zabbix plugin 4.6 does not substitute dashboard variables in queries sent with expressions.
        for fname, d in self.dashes.items():
            self.assertNotIn('__expr__', json.dumps(d), fname)

    def test_no_refid_overrides(self):
        # The plugin's frontend drops refId of history frames (short ranges): match by name instead.
        for fname, d in self.dashes.items():
            self.assertNotIn('byFrameRefID', json.dumps(d), fname)

    def test_panels_follow_the_time_picker(self):
        # Only "current value" panels read a fixed last 24 h; history follows the selected period.
        for fname, d in self.dashes.items():
            for p in panels(d):
                with self.subTest(dashboard=fname, panel=p['title']):
                    self.assertIn(p.get('timeFrom'), (None, '24h'))
                    self.assertNotIn('этот год', p['title'].lower())

    def test_unique_uids_and_ids(self):
        uids = [d['uid'] for d in self.dashes.values()]
        self.assertEqual(len(uids), len(set(uids)))
        for fname, d in self.dashes.items():
            ids = [p['id'] for p in panels(d)]
            self.assertEqual(len(ids), len(set(ids)), fname)

    def test_panels_do_not_overlap(self):
        for fname, d in self.dashes.items():
            taken = set()
            for p in d['panels']:
                g = p['gridPos']
                self.assertLessEqual(g['x'] + g['w'], 24, (fname, p['title']))
                cells = {(x, y) for x in range(g['x'], g['x'] + g['w']) for y in range(g['y'], g['y'] + g['h'])}
                self.assertFalse(cells & taken, (fname, p['title']))
                taken |= cells

    def test_baked_in_thresholds_default_to_the_template_macros(self):
        sys.path.insert(0, os.path.join(VMW, 'tools'))
        import gen_grafana_dashboards as gen
        macros = {m['macro']: m['value'] for m in load_template()['macros']}
        self.assertEqual(gen.CFG, {
            'crit': int(macros['{$VMW.FORECAST.CRIT}']), 'warn': int(macros['{$VMW.FORECAST.WARN}']),
            'horizon': int(macros['{$VMW.FORECAST.HORIZON}'].rstrip('d')),
            'ds_pfree_min': int(macros['{$VMW.DS.PFREE.MIN}']), 'cpu_max': int(macros['{$VMW.CL.CPU.MAX}']),
            'mem_max': int(macros['{$VMW.CL.MEM.MAX}'])})

    def test_no_placeholder_left_and_overridden_thresholds_reach_the_dashboards(self):
        for d in self.dashes.values():
            self.assertNotRegex(json.dumps(d, ensure_ascii=False), r'@[A-Z]+@')
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.run([sys.executable, os.path.join(VMW, 'tools', 'gen_grafana_dashboards.py'), tmp,
                            '--crit', '60', '--warn', '120', '--horizon', '180', '--ds-pfree-min', '15',
                            '--cpu-max', '70', '--mem-max', '90'], check=True, stdout=subprocess.DEVNULL)
            with open(os.path.join(tmp, 'vmware-datastores.json')) as fh:
                text = fh.read()
            with open(os.path.join(tmp, 'vmware-cpu-memory.json')) as fh:
                cpu = fh.read()
        self.assertIn('Через 180 дн.', text)
        self.assertIn('Меньше 60 дней', text)
        self.assertIn('(15 %)', text)
        self.assertIn('(70 %)', cpu)
        self.assertIn('(90 %)', cpu)
        self.assertNotIn('Через 90 дн', text)

    def test_item_regexes_escape_everything_special(self):
        sys.path.insert(0, os.path.join(VMW, 'tools'))
        import gen_grafana_dashboards as gen
        self.assertEqual(gen.rx('Datastore [$datastore]: used, p.p.'),
                         '/^Datastore \\[($datastore)\\]: used, p\\.p\\.$/')
        rx_ = gen.rx('used/free ratio {avg}|max *')
        self.assertEqual(rx_, '/^used\\/free ratio \\{avg\\}\\|max \\*$/')
        self.assertTrue(re.search(rx_[1:-1], 'used/free ratio {avg}|max *'))
        self.assertFalse(re.search(rx_[1:-1], 'usedXfree ratio avgmax'))

    def test_energy_is_summed_per_hour_on_local_day_boundaries(self):
        power = self.dashes['vmware-power.json']
        tz = next(v for v in power['templating']['list'] if v['name'] == 'tz')
        self.assertEqual(tz['current']['value'], '3h')
        # a zero shift is rejected by the plugin: UTC+0 is a whole day, which keeps the UTC boundaries
        self.assertEqual({o['text']: o['value'] for o in tz['options']}['UTC+0'], '24h')
        self.assertNotIn('0h', [o['value'] for o in tz['options']])
        bars = next(p for p in power['panels'] if p['title'].startswith('Энергия по дням'))
        funcs = [(f['def']['name'], f['params']) for f in bars['targets'][0]['functions']]
        self.assertEqual(funcs, [('sumSeries', []), ('groupBy', ['1h', 'avg']), ('timeShift', ['$tz']),
                                 ('groupBy', ['1d', 'sum']), ('timeShift', ['+$tz']), ('scale', ['0.001']),
                                 ('setAlias', ['за период'])])
        # no daily mean times 24: it overstated the partial days at both ends of the period
        self.assertNotIn('0.024', json.dumps(power))

    def test_generator_output_is_committed(self):
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.run([sys.executable, os.path.join(VMW, 'tools', 'gen_grafana_dashboards.py'), tmp],
                           check=True, stdout=subprocess.DEVNULL)
            for path in DASHBOARDS:
                with open(path) as committed, open(os.path.join(tmp, os.path.basename(path))) as fresh:
                    self.assertEqual(committed.read(), fresh.read(), 'regenerate ' + os.path.basename(path))


if __name__ == '__main__':
    unittest.main()
