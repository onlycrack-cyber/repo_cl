"""Checks the VMware capacity template and the vmware/grafana dashboards.

Both are generated by vmware/tools; the tests also make sure the committed
files are what the generators produce, so nobody edits the output by hand.
"""
import glob
import json
import os
import re
import subprocess
import sys
import tempfile
import unittest

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VMW = os.path.join(ROOT, 'vmware')
TEMPLATE = os.path.join(VMW, 'zbx_template_vmware_capacity.yaml')
DASHBOARDS = sorted(glob.glob(os.path.join(VMW, 'grafana', '*.json')))

# Names of the standard "VMware" / "VMware Hypervisor" template items the dashboards use.
STANDARD_NAMES = [
    'CPU usage', 'CPU usage in percent', 'Used memory', 'Total memory', 'CPU cores', 'CPU frequency',
    'Power usage', 'Power usage maximum allowed',
    'Free space on datastore [DS-01] (percentage)', 'Total size of datastore [DS-01]',
]
LLD_SAMPLES = {'{#DATASTORE}': 'DS-01', '{#CLUSTER.NAME}': 'Cluster-A'}
# Dashboard variables substituted by a sample value before matching.
VAR_SAMPLES = {'$datastore': 'DS-01', '$cluster': 'Cluster-A'}


def load_template():
    with open(TEMPLATE) as fh:
        return yaml.safe_load(fh)['zabbix_export']['templates'][0]


def prototypes(tpl):
    return [p for r in tpl['discovery_rules'] for p in r['item_prototypes']]


def all_uuids(node):
    if isinstance(node, dict):
        for k, v in node.items():
            if k == 'uuid':
                yield v
            else:
                yield from all_uuids(v)
    elif isinstance(node, list):
        for v in node:
            yield from all_uuids(v)


class TemplateTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tpl = load_template()
        cls.protos = prototypes(cls.tpl)
        with open(TEMPLATE) as fh:
            cls.text = fh.read()

    def test_uuids_are_unique_v4(self):
        uuids = list(all_uuids(self.tpl))
        self.assertEqual(len(uuids), len(set(uuids)))
        for u in uuids:
            self.assertRegex(u, r'^[0-9a-f]{12}4[0-9a-f]{3}[89ab][0-9a-f]{15}$')

    def test_item_keys_unique_and_namespaced(self):
        keys = [p['key'] for p in self.protos]
        self.assertEqual(len(keys), len(set(keys)))
        for k in keys:
            self.assertTrue(k.startswith('vmw.cap.'), k)

    def test_discovery_keys_differ_from_standard_template(self):
        # The standard VMware template owns the unquoted keys; duplicates would fail the link.
        for r in self.tpl['discovery_rules']:
            self.assertIn('["{$VMWARE.URL}"]', r['key'])

    def test_triggers_reference_own_prototypes(self):
        keys = {p['key'] for p in self.protos}
        refs = 0
        for p in self.protos:
            for t in p.get('trigger_prototypes', []):
                for expr in (t['expression'], t.get('recovery_expression', '')):
                    for key in re.findall(r'/VMware capacity planning/([^)]+)\)', expr):
                        self.assertIn(key, keys, t['name'])
                        refs += 1
        self.assertGreater(refs, 0)

    def test_warning_triggers_depend_on_high(self):
        for p in self.protos:
            for t in p.get('trigger_prototypes', []):
                if t['priority'] == 'WARNING':
                    self.assertTrue(t.get('dependencies'), t['name'])

    def test_used_macros_are_defined(self):
        defined = {m['macro'] for m in self.tpl['macros']}
        used = set(re.findall(r'\{\$VMW\.[A-Z.]+\}', self.text))
        self.assertEqual(used - defined, set())
        self.assertEqual(defined - used, set())

    def test_foreach_filters_match_two_parameter_keys(self):
        # vmware.hv.* keys take [url,uuid]; "[*]" would silently match nothing.
        refs = re.findall(r'/\*/(vmware\.hv\.[a-z.]+)\[([^\]]*)\]\?', self.text)
        self.assertTrue(refs)
        for key, params in refs:
            self.assertTrue(params.startswith('*,*'), key + '[' + params + ']')

    def test_long_trends_for_year_over_year(self):
        for p in self.protos:
            if p.get('value_type', 'FLOAT') in ('FLOAT', 'UNSIGNED'):
                self.assertEqual(p.get('trends'), '730d', p['key'])

    def test_generator_output_is_committed(self):
        with tempfile.TemporaryDirectory() as tmp:
            out = os.path.join(tmp, 't.yaml')
            subprocess.run([sys.executable, os.path.join(VMW, 'tools', 'gen_capacity_template.py'), out],
                           check=True, stdout=subprocess.DEVNULL)
            with open(out) as fh:
                self.assertEqual(fh.read(), self.text, 'regenerate vmware/zbx_template_vmware_capacity.yaml')


def known_names():
    names = list(STANDARD_NAMES)
    for p in prototypes(load_template()):
        name = p['name']
        for macro, value in LLD_SAMPLES.items():
            name = name.replace(macro, value)
        assert '{#' not in name, 'add a sample for ' + name
        names.append(name)
    return names


def item_matches(item_filter, name):
    for var, value in VAR_SAMPLES.items():
        item_filter = item_filter.replace(var, value)
    if item_filter.startswith('/') and item_filter.endswith('/'):
        return re.search(item_filter[1:-1], name) is not None
    return item_filter == name


def panels(dash):
    for p in dash['panels']:
        yield p
        for sub in p.get('panels', []):
            yield sub


class DashboardTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.names = known_names()
        cls.dashes = {}
        for path in DASHBOARDS:
            with open(path) as fh:
                cls.dashes[os.path.basename(path)] = json.load(fh)

    def test_three_dashboards(self):
        self.assertEqual(sorted(self.dashes),
                         ['vmware-cpu-memory.json', 'vmware-datastores.json', 'vmware-power.json'])

    def test_every_item_filter_matches_an_item(self):
        for fname, d in self.dashes.items():
            for p in panels(d):
                for t in p.get('targets', []):
                    if 'item' not in t:
                        continue
                    flt = t['item']['filter']
                    with self.subTest(dashboard=fname, panel=p['title']):
                        self.assertTrue(any(item_matches(flt, n) for n in self.names),
                                        '%r matches no item' % flt)

    def test_variable_queries_match_items(self):
        for fname, d in self.dashes.items():
            for v in d['templating']['list']:
                item = (v.get('query') or {}).get('item') if v['type'] == 'query' else None
                if item:
                    self.assertTrue(any(item_matches(item, n) for n in self.names), (fname, v['name']))
                    self.assertEqual(v.get('refresh'), 2, (fname, v['name']))

    def test_no_server_side_expressions(self):
        # Zabbix plugin 4.6 does not substitute dashboard variables in queries sent with expressions.
        for fname, d in self.dashes.items():
            self.assertNotIn('__expr__', json.dumps(d), fname)

    def test_unique_uids_and_ids(self):
        uids = [d['uid'] for d in self.dashes.values()]
        self.assertEqual(len(uids), len(set(uids)))
        for fname, d in self.dashes.items():
            ids = [p['id'] for p in panels(d)]
            self.assertEqual(len(ids), len(set(ids)), fname)

    def test_panels_do_not_overlap(self):
        for fname, d in self.dashes.items():
            taken = set()
            for p in d['panels']:
                g = p['gridPos']
                self.assertLessEqual(g['x'] + g['w'], 24, (fname, p['title']))
                cells = {(x, y) for x in range(g['x'], g['x'] + g['w']) for y in range(g['y'], g['y'] + g['h'])}
                self.assertFalse(cells & taken, (fname, p['title']))
                taken |= cells

    def test_generator_output_is_committed(self):
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.run([sys.executable, os.path.join(VMW, 'tools', 'gen_grafana_dashboards.py'), tmp],
                           check=True, stdout=subprocess.DEVNULL)
            for path in DASHBOARDS:
                with open(path) as committed, open(os.path.join(tmp, os.path.basename(path))) as fresh:
                    self.assertEqual(committed.read(), fresh.read(), 'regenerate ' + os.path.basename(path))


if __name__ == '__main__':
    unittest.main()
